"""Части скрипта фактов: по одной на технологию, из которой сделан сервис.

Зачем. Скрипт фактов tools/extract.py сам про технологии не знает: что вынуть из compose, из живой схемы методов
FastAPI, из живой базы Postgres, из тестов pytest — знает часть с этим именем. У сервиса в реестре
project/services.yaml в поле facts перечислены его части; каждая часть кладёт в .facts.json свой раздел под своим
именем.

Части (файл — tools/facts/<часть>.py; дефис в имени — как в реестре):
  compose            порт, тома, переменные, команда запуска, проверка здоровья — из compose-файла проекта;
  pydantic-settings  настройки из классов BaseSettings и чтения os.environ в коде на Python;
  vite-env           переменные окружения, которые читает интерфейс на Vite (import.meta.env, process.env);
  fastapi-openapi    методы из живой схемы /openapi.json: обработчик в коде, поля запроса и ответа, нужен ли вход;
  postgres           своя база: таблицы, колонки, типы, описания колонок из моделей, уникальные ключи, число строк;
  alembic            миграции базы: папка, сколько их, какая применена;
  python-imports     какие общие пакеты проекта импортирует код;
  python-exports     что общий пакет даёт наружу: имена из __all__ и их подписи;
  pytest             сколько тестов собрано; с --tests — итог прогона;
  vitest             сколько тестов интерфейса — подсчётом в файлах, без запуска.

Договор части — модуль с:
  NEEDS = ("compose", …)       какие части должны отработать раньше (их разделы — в ctx.facts); можно не задавать;
  CODE_EXTS = (".py", …)       расширения файлов кода, если часть знает язык сервиса — по ним считаются строки кода;
  extract(ctx) -> dict          раздел .facts.json; ctx — запись реестра, настройки проекта, разделы прежних частей;
  compare(old, new) -> list     расхождения для живой проверки (extract.py --check), строками; [] — совпадает.
Общие помощники — tools/facts/_base.py.

Новая технология — новая часть: файл tools/facts/<имя>.py по договору выше, имя — в поле facts реестра.
Неизвестное имя части в реестре — ошибка скрипта, а не тихий пропуск.
"""
